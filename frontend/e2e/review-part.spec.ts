import { expect } from '@playwright/test'
import { test, apiGet, loginViaLink } from './support'

test('Verifica questa parte: selezione, job in mock, avviso visibile e pannello sull’unità', async ({ page }) => {
  await loginViaLink(page)
  const [lesson] = await apiGet<{ id: number }[]>(page.request, '/lessons?materia=VERIFICA PARTE')
  await page.goto(`/lezioni/${lesson.id}`)
  const doc = page.getByTestId('lesson-document')
  const paragraph = doc.locator('.cm-line', { hasText: 'un’impostazione' }).first()
  await expect(paragraph).toBeVisible()
  await paragraph.click()
  await page.keyboard.press('Home')
  await page.keyboard.press('Shift+End')
  const selected = await page.evaluate(() => window.getSelection()?.toString())
  expect(selected?.trim()).toBeTruthy()
  const posted = page.waitForRequest(request => request.url().endsWith(`/lessons/${lesson.id}/jobs`) && request.method() === 'POST')
  await paragraph.click({ button: 'right' })
  const verify = page.getByRole('menuitem', { name: 'Verifica questa parte' })
  await expect(verify).not.toHaveAttribute('aria-disabled')
  await verify.click()
  const payload = (await posted).postDataJSON()
  expect(payload.type).toBe('review_part')
  expect(payload.parts).toHaveLength(1)
  expect(payload.parts[0].unit_id).toBe('1.1')
  expect(payload.parts[0].anchor.quote).toBe(selected)
  const notice = page.getByTestId('part-review-notice')
  await expect(notice).toBeVisible()
  await expect(notice).toContainText(/\d+ issue trovate/, { timeout: 30_000 })
  const issues = await apiGet<{ items: { issue: { origin: string; unit_id: string } }[] }>(page.request, `/lessons/${lesson.id}/issues?status=all`)
  expect(issues.items.length).toBeGreaterThan(0)
  expect(issues.items.every(item => item.issue.origin === 'parte' && item.issue.unit_id === '1.1')).toBe(true)
  await expect(notice).toContainText(`${issues.items.length} issue trovate`)
  const viewport = page.viewportSize()!
  const box = (await notice.boundingBox())!
  expect(box.y + box.height).toBeLessThanOrEqual(viewport.height)
  expect(box.y).toBeGreaterThan(viewport.height / 2)
  await notice.getByRole('link', { name: 'Apri Verifica' }).click()
  await expect(page).toHaveURL(/panel=verifica.*review_unit=1\.1/)
  const panel = page.getByTestId('lesson-review-panel')
  await expect(panel).toBeVisible()
  await expect(panel.locator('[data-unit="1.1"] [data-testid="review-issue-group"]')).toBeVisible()
  await expect(panel.getByTestId('issue-detail')).toBeVisible()
})
